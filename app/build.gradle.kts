android {
    namespace = "com.ps2gamepad"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.ps2gamepad"
        minSdk = 28 // BluetoothHidDevice was added in API 28
        targetSdk = 35
        versionCode = 25
        versionName = "3.7.0"
    }

    // Release signing comes from keystore.properties (git-ignored, never committed).
    // Without it the release APK is built unsigned.
    val keystoreFile = rootProject.file("keystore.properties")
    val keystore = Properties().apply { if (keystoreFile.exists()) keystoreFile.inputStream().use { load(it) } }
    signingConfigs {
        if (keystoreFile.exists()) {
            create("release") {
                storeFile = rootProject.file(keystore.getProperty("storeFile"))
                storePassword = keystore.getProperty("storePassword")
                keyAlias = keystore.getProperty("keyAlias")
                keyPassword = keystore.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
        debug {
            // Same package as release on purpose: only one app can hold the HID registration.
            versionNameSuffix = "-debug"
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
    }
    testOptions {
        unitTests.isReturnDefaultValues = true
        unitTests.isIncludeAndroidResources = true
        unitTests.all {
            // ./gradlew testDebugUnitTest -Pscreenshots  -> renders docs/screenshots/*.png
            if (project.hasProperty("screenshots")) it.systemProperty("screenshotDir", rootProject.file("docs/screenshots").absolutePath)
        }
    }
}

